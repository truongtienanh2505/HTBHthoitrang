CREATE   PROCEDURE [dbo].[sp_RebuildProductPromotionsCache]
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @Now DATETIME2(0) = SYSUTCDATETIME();

    BEGIN TRAN;

        TRUNCATE TABLE dbo.ProductPromotions;

        ;WITH ActivePromo AS (
            SELECT km.MaKhuyenMai, km.LoaiGiamGia, km.GiaTriGiam, km.GiamToiDa, km.UuTien
            FROM dbo.KhuyenMai km
            WHERE km.KichHoat = 1
              AND km.BatDau <= @Now
              AND km.KetThuc >  @Now
        ),
        VariantPrice AS (
            SELECT
                bt.MaBienThe,
                sp.MaSanPham,
                CAST(sp.GiaGoc + bt.DieuChinhGia AS DECIMAL(18,2)) AS GiaHienTai
            FROM dbo.BienTheSanPham bt
            JOIN dbo.SanPham sp ON sp.MaSanPham = bt.MaSanPham
            WHERE sp.HoatDong = 1 AND bt.HoatDong = 1
        ),
        Candidate AS (
            SELECT
                vp.MaBienThe,
                vp.MaSanPham,
                ap.MaKhuyenMai,
                ap.UuTien,
                vp.GiaHienTai AS GiaGoc,
                CAST(
                    CASE
                        WHEN ap.LoaiGiamGia = 'PERCENTAGE' THEN
                            CASE
                                WHEN ap.GiamToiDa IS NULL THEN (vp.GiaHienTai * ap.GiaTriGiam / 100.0)
                                ELSE
                                    CASE
                                        WHEN (vp.GiaHienTai * ap.GiaTriGiam / 100.0) > ap.GiamToiDa THEN ap.GiamToiDa
                                        ELSE (vp.GiaHienTai * ap.GiaTriGiam / 100.0)
                                    END
                            END
                        WHEN ap.LoaiGiamGia = 'FIXED_AMOUNT' THEN
                            CASE
                                WHEN ap.GiaTriGiam > vp.GiaHienTai THEN vp.GiaHienTai
                                ELSE ap.GiaTriGiam
                            END
                        ELSE 0
                    END
                AS DECIMAL(18,2)) AS SoTienGiam
            FROM VariantPrice vp
            JOIN dbo.SanPhamKhuyenMai spkm ON spkm.MaSanPham = vp.MaSanPham
            JOIN ActivePromo ap ON ap.MaKhuyenMai = spkm.MaKhuyenMai
        ),
        Ranked AS (
            SELECT
                c.*,
                CAST(c.GiaGoc - c.SoTienGiam AS DECIMAL(18,2)) AS GiaSauGiam,
                ROW_NUMBER() OVER (
                    PARTITION BY c.MaBienThe
                    ORDER BY c.SoTienGiam DESC, c.UuTien DESC, c.MaKhuyenMai ASC
                ) AS rn
            FROM Candidate c
        )
        INSERT INTO dbo.ProductPromotions(MaBienThe, MaSanPham, MaKhuyenMai, GiaGoc, SoTienGiam, GiaSauGiam, CapNhatLuc)
        SELECT
            vp.MaBienThe,
            vp.MaSanPham,
            r.MaKhuyenMai,
            vp.GiaHienTai,
            COALESCE(r.SoTienGiam, 0),
            COALESCE(r.GiaSauGiam, vp.GiaHienTai),
            @Now
        FROM VariantPrice vp
        LEFT JOIN Ranked r
               ON r.MaBienThe = vp.MaBienThe
              AND r.rn = 1;

    COMMIT;
END
GO
