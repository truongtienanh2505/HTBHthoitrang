-- Top san pham ban chay theo ngay (dua tren ChiTietDonHang) - bo qua don DaHuy/ThatBai
CREATE VIEW [dbo].[vw_TopSanPhamBanChayTheoNgay]
AS
SELECT
    CAST(dh.NgayDat AS date) AS Ngay,
    ctdh.Snapshot_TenSanPham AS TenSanPham,
    SUM(ctdh.SoLuong) AS TongSoLuong
FROM dbo.DonHang dh
JOIN dbo.ChiTietDonHang ctdh ON ctdh.MaDonHang = dh.MaDonHang
WHERE dh.MaTrangThai IN (4) -- Thanh cong
GROUP BY CAST(dh.NgayDat AS date), ctdh.Snapshot_TenSanPham;

