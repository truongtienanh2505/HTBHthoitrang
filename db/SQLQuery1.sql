-- Canh bao san pham sap het hang (tinh theo bien the)
CREATE VIEW [dbo].[vw_CanhBaoSapHetHang]
AS
SELECT
    sp.MaSanPham, sp.TenSanPham, sp.Slug,
    SUM(bt.SoLuongTon) AS TongTon
FROM dbo.SanPham sp
JOIN dbo.BienTheSanPham bt ON bt.MaSanPham = sp.MaSanPham
